subroutine write_scalar_block(nunit, file_in, scalar_list)

implicit none

integer, parameter :: l_name=16, l_unit=25, l_desc=60

integer, intent(in) :: nunit
character(len=*), intent(in) :: file_in
double precision, intent(in), dimension(*) :: scalar_list

integer :: nvars, jid
character(len=l_name), allocatable, dimension(:) :: s_name
character(len=l_unit), allocatable, dimension(:) :: s_unit
character(len=l_desc), allocatable, dimension(:) :: s_desc
integer, external :: get_nvars

101 format('    "', A, '": {"units": "', A, '", "long_name": "', A, '", "data": ', es15.8, '},')

nvars = get_nvars(file_in)
