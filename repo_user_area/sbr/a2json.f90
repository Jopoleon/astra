subroutine write_arr(nunit, ndim, arr, sname, sunit, sdesc)

implicit none

integer, parameter :: l_name=16, l_unit=25, l_desc=60

integer, intent(in) :: nunit, ndim
double precision, intent(in), dimension(ndim) :: arr
character(len=*), intent(in) :: sname, sunit, sdesc

integer :: i
double precision :: abs_val
double precision, dimension(ndim) :: array

102 format('    "', A, '": {"ndim": ', i0, ', "units": "', A, '", "long_name": "', A, '", "data": [')
write(nunit, 102) TRIM(sname), ndim, TRIM(sunit), TRIM(sdesc)

do i=1, ndim
    abs_val = ABS(arr(i))
    if (abs_val < 1e-20 .or. abs_val > 1e20) then
        array(i) = 0.
    else
        array(i) = arr(i)
    endif
enddo

if (MAXVAL(ABS(array)) > 0.) then
    write(nunit, '(5(es15.8, ","))') (array(i), i=1, ndim-1)
    write(nunit, '(es15.8)') array(ndim) ! No comma after last array entry
endif

return
end subroutine write_arr

!---------------------------------------------------------------
integer function get_nvars(file_in)

implicit none

integer, parameter :: nunit=31

character(len=*), intent(in) :: file_in

integer :: ios

get_nvars = 0
open(nunit, file=TRIM(file_in), iostat=ios)
read(nunit, '(/A)')
do
    read(nunit, '(A)', iostat=ios)
    if (ios /= 0) EXIT
    get_nvars = get_nvars + 1
enddo
close(nunit)

return
end function get_nvars

!---------------------------------------------------------------
subroutine getAttributes(file_in, nvars, s_name, s_desc, s_unit)

implicit none


integer, parameter :: nunit=31, l_name=16, l_unit=25, l_desc=60

integer, intent(in) :: nvars
character(len=*), intent(in) :: file_in
character(len=l_name), intent(out), dimension(nvars) :: s_name
character(len=l_desc), intent(out), dimension(nvars) :: s_desc
character(len=l_unit), intent(out), dimension(nvars) :: s_unit

character(len=l_name) :: sname
character(len=l_desc) :: sdesc
character(len=l_unit) :: sunit

integer :: ios, varid

varid = 0
open(nunit, file=TRIM(file_in), iostat=ios)
read(nunit, '(/A)')
do
    read(nunit, '(A16, X, A25, X, A60)', iostat=ios) sname, sunit, sdesc
    if (ios /= 0) EXIT
    varid = varid + 1
    s_name(varid) = sname
    s_unit(varid) = sunit
    s_desc(varid) = sdesc
enddo
close(nunit)

return
end subroutine getAttributes
